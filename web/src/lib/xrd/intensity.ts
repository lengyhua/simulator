/**
 * Peak intensity and reflection multiplicity (plan §3.2 / T06):
 *
 *   I_hkl = K · Lp(2θ) · |F|² · mult          (K = 1, plan §4.1)
 *
 * `mult` counts the Laue-equivalent planes of (h,k,l): the distinct images
 * under the space-group rotation matrices ({@link laueOperations}), with
 * Friedel pairs included. For centrosymmetric groups the point group already
 * contains the inversion; adding Friedel pairs explicitly keeps the count
 * correct for non-centrosymmetric groups too.
 *
 * Equivalent hkl merging is NOT done here: the pipeline enumerates a single
 * canonical representative per orbit (h≥k≥l≥0), so every reflection reaching
 * this layer is already distinct.
 */

import { K } from './constants';
import { lorentzPolarization } from './lorentz';
import { laueOperations } from './wyckoff';
import type { HKLReflection } from './types';

/** Options for {@link peakIntensity} / {@link reflectionIntensity}. */
export interface IntensityOptions {
  /** Apply the Lorentz–polarization factor (useLp checkbox). */
  useLp: boolean;
  /** Scale factor K (defaults to {@link K} = 1). */
  k?: number;
}

/** Squared modulus of a complex structure factor. */
export function modulusSquared(f: { re: number; im: number }): number {
  return f.re * f.re + f.im * f.im;
}

/**
 * Peak intensity without multiplicity: `I = K · Lp · |F|²` (plan §3.2).
 * Multiply by `mult` (see {@link reflectionMultiplicity}) for the full
 * reflection intensity, or use {@link reflectionIntensity} directly.
 */
export function peakIntensity(
  twoThetaDeg: number,
  f: { re: number; im: number },
  opts: IntensityOptions,
): number {
  const k = opts.k ?? K;
  const lp = opts.useLp ? lorentzPolarization(twoThetaDeg) : 1;
  return k * lp * modulusSquared(f);
}

/**
 * Full reflection intensity `I_hkl = K · Lp · |F|² · mult`.
 */
export function reflectionIntensity(
  twoThetaDeg: number,
  f: { re: number; im: number },
  multiplicity: number,
  opts: IntensityOptions,
): number {
  return peakIntensity(twoThetaDeg, f, opts) * multiplicity;
}

/**
 * Laue multiplicity of reflection (h,k,l): the number of distinct planes
 * generated by the space-group rotations plus Friedel pairs.
 *
 * Spot checks (cubic m-3m): (100)=6, (110)=12, (111)=8, (220)=12, (311)=24,
 * (400)=6 (plan §5-T06 acceptance 4).
 *
 * @throws Error when the space group is unknown.
 */
export function reflectionMultiplicity(sgKey: string, h: number, k: number, l: number): number {
  const matrices = laueOperations(sgKey);
  const distinct: number[][] = [];
  const seen = (v: number[]): boolean =>
    distinct.some((d) => d[0] === v[0] && d[1] === v[1] && d[2] === v[2]);
  const push = (v: number[]): void => {
    if (!seen(v)) {
      distinct.push(v);
    }
  };
  for (const m of matrices) {
    const v0 = m[0] * h + m[1] * k + m[2] * l;
    const v1 = m[3] * h + m[4] * k + m[5] * l;
    const v2 = m[6] * h + m[7] * k + m[8] * l;
    push([v0, v1, v2]);
    push([-v0, -v1, -v2]); // Friedel pair
  }
  return distinct.length;
}

/**
 * Normalizes reflection intensities so the strongest peak is 100
 * (plan §3.2). Returns new reflection objects — inputs are not mutated.
 * An empty list stays empty; a zero-intensity list normalizes to all-zero.
 */
export function normalizeReflections(rs: HKLReflection[]): HKLReflection[] {
  if (rs.length === 0) {
    return [];
  }
  let max = 0;
  for (const r of rs) {
    if (r.intensity > max) {
      max = r.intensity;
    }
  }
  // Divide-then-scale (not multiply by a precomputed 100/max): for the
  // strongest reflection max/max·100 is exactly 100, whereas max·(100/max)
  // drifts by one ulp (99.99999999999999) and breaks equality assertions.
  return rs.map((r) => ({ ...r, intensityNorm: max > 0 ? (r.intensity / max) * 100 : 0 }));
}
